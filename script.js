const categoryNames = {
  kitchen: "kitchen",
  washroom: "washroom",
  sewing: "sewing basket",
  sitting: "sitting room",
  garden: "garden",
  writing: "writing desk"
};




const entriesContainer =
  document.getElementById("entries-container");

const emptyMessage =
  document.getElementById("empty-message");

const tabs = document.querySelectorAll(".tab[data-category]");

const pagination =
  document.getElementById("pagination");



const entriesPerPage = 5;

let currentPage = 1;
let currentCategory = "all";
let currentEntry = null;



function entrySlug(title) {
  return title
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}


function readAddress() {

  const params = new URLSearchParams(
    window.location.search
  );

  const category = params.get("category");

  currentCategory =
    category === "all" ||
    Object.hasOwn(categoryNames, category)
      ? category
      : "all";

  const page = Number(params.get("page"));

  currentPage =
    Number.isSafeInteger(page) && page > 0
      ? page
      : 1;

  currentEntry = params.get("entry");

}



function updateAddress() {

  const url = new URL(window.location.href);

  url.searchParams.delete("category");
  url.searchParams.delete("page");
  url.searchParams.delete("entry");

  if (currentEntry) {

    url.searchParams.set("entry", currentEntry);

  } else {

    if (currentCategory !== "all") {
      url.searchParams.set(
        "category",
        currentCategory
      );
    }

    if (currentPage > 1) {
      url.searchParams.set(
        "page",
        currentPage
      );
    }

  }

  window.history.pushState({}, "", url);

}



function updateTabs() {

  tabs.forEach(tab => {

    const selected =
      !currentEntry &&
      tab.dataset.category === currentCategory;

    tab.classList.toggle("active", selected);

    if (selected) {
      tab.setAttribute("aria-current", "true");
    } else {
      tab.removeAttribute("aria-current");
    }

  });

}



function scrollToTop() {

  const journal = document.querySelector(".journal");

  if (!journal) return;

  journal.scrollTo({
    top: 0,
    behavior: window.matchMedia(
      "(prefers-reduced-motion: reduce)"
    ).matches ? "instant" : "smooth"
  });

}



function getEntryUrl(entry) {

  const url = new URL(window.location.href);

  url.searchParams.delete("category");
  url.searchParams.delete("page");

  url.searchParams.set(
    "entry",
    entrySlug(entry.title)
  );

  url.hash = "";

  return url.href;

}


async function copyEntryLink(entry, button) {

  const link = getEntryUrl(entry);

  try {

    await navigator.clipboard.writeText(link);

    button.textContent = "copied !";

    // restore the label when focus leaves the button
    button.addEventListener(
      "blur",
      () => {
        button.textContent = "copy link";
      },
      { once: true }
    );

  } catch (error) {


    window.prompt(
      "copy this little note's address :",
      link
    );

  }

}



function createEntry(entry) {

  const article = document.createElement("article");
  article.className = "entry";


  const categoryLabel =
    document.createElement("span");

  categoryLabel.className = "entry-category";

  categoryLabel.textContent =
    categoryNames[entry.category] || entry.category;

  article.appendChild(categoryLabel);



  const title = document.createElement("h2");
  title.className = "entry-title";

  const titleLink = document.createElement("a");
  titleLink.className = "entry-title-link";
  titleLink.href = getEntryUrl(entry);
  titleLink.textContent = entry.title;

  titleLink.addEventListener("click", event => {

    if (
      event.ctrlKey ||
      event.metaKey ||
      event.shiftKey ||
      event.altKey ||
      event.button !== 0
    ) {
      return;
    }

    event.preventDefault();

    const slug = entrySlug(entry.title);

    if (currentEntry === slug) {
      return;
    }

    currentEntry = slug;

    updateAddress();
    renderEntries();
    scrollToTop();

  });

  title.appendChild(titleLink);
  article.appendChild(title);



  const linkButton = document.createElement("button");

  linkButton.type = "button";
  linkButton.className = "entry-link";
  linkButton.textContent = "copy link";

  linkButton.setAttribute(
    "aria-label",
    `copy link to ${entry.title}`
  );

  linkButton.addEventListener("click", () => {
    copyEntryLink(entry, linkButton);
  });

  article.appendChild(linkButton);


  const content = document.createElement("div");
  content.className = "entry-content";

  entry.content.forEach(paragraph => {

    const p = document.createElement("p");
    p.textContent = paragraph;

    content.appendChild(p);

  });

  article.appendChild(content);


  if (entry.footnotes && entry.footnotes.length > 0) {

    const footnotes = document.createElement("aside");
    footnotes.className = "entry-footnotes";

    const label = document.createElement("span");
    label.className = "footnote-label";
    label.textContent = "footnotes";

    footnotes.appendChild(label);

    entry.footnotes.forEach(note => {

      const p = document.createElement("p");
      p.textContent = note;

      footnotes.appendChild(p);

    });

    article.appendChild(footnotes);

  }

  return article;

}



function renderEntries() {

  entriesContainer.replaceChildren();
  pagination.replaceChildren();

  updateTabs();


  if (currentEntry) {

    const entry = entries.find(item =>
      entrySlug(item.title) === currentEntry
    );

    emptyMessage.hidden = Boolean(entry);

    if (!entry) {
      emptyMessage.textContent =
        "this little note could not be found ..";
      return;
    }

    emptyMessage.textContent =
      "there are no notes here just yet ..";


    const backLink = document.createElement("a");
    backLink.href = window.location.pathname;
    backLink.className = "back-to-journal";
    backLink.textContent = "‹ back to the journal";

    backLink.addEventListener("click", event => {

      event.preventDefault();

      currentEntry = null;
      currentCategory = "all";
      currentPage = 1;

      updateAddress();
      renderEntries();
      scrollToTop();

    });

    entriesContainer.appendChild(backLink);
    entriesContainer.appendChild(createEntry(entry));

    return;
  }


  const filteredEntries = entries.filter(entry =>
    currentCategory === "all" ||
    entry.category === currentCategory
  );

  const totalPages = Math.ceil(
    filteredEntries.length / entriesPerPage
  );

  currentPage = Math.max(
    1,
    Math.min(currentPage, totalPages || 1)
  );

  const startIndex =
    (currentPage - 1) * entriesPerPage;

  const visibleEntries = filteredEntries.slice(
    startIndex,
    startIndex + entriesPerPage
  );

  emptyMessage.hidden = filteredEntries.length > 0;

  emptyMessage.textContent =
    "there are no notes here just yet ..";

  visibleEntries.forEach(entry => {
    entriesContainer.appendChild(createEntry(entry));
  });

  renderPagination(totalPages);

}



function renderPagination(totalPages) {

  pagination.replaceChildren();

  if (totalPages <= 1) {
    return;
  }

  pagination.appendChild(
    createPageButton(
      "‹",
      currentPage - 1,
      currentPage === 1,
      "previous page"
    )
  );

  for (let page = 1; page <= totalPages; page++) {

    const button = createPageButton(
      page,
      page,
      false,
      `page ${page}`
    );

    if (page === currentPage) {
      button.classList.add("active");
      button.setAttribute("aria-current", "page");
    }

    pagination.appendChild(button);

  }

  pagination.appendChild(
    createPageButton(
      "›",
      currentPage + 1,
      currentPage === totalPages,
      "next page"
    )
  );

}



function createPageButton(
  label,
  page,
  disabled = false,
  description = ""
) {

  const button = document.createElement("button");

  button.type = "button";
  button.className = "page-button";
  button.textContent = label;
  button.disabled = disabled;

  button.setAttribute(
    "aria-label",
    description || `page ${page}`
  );

  button.addEventListener("click", () => {

    if (disabled || page === currentPage) {
      return;
    }

    currentPage = page;

    updateAddress();
    renderEntries();
    scrollToTop();

  });

  return button;

}



